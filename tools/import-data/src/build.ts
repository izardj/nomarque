// Assembles the parsed CSV rows into a validated GameData object and renders
// the generated TypeScript files. Rendering is deterministic: the same sources
// always produce the same bytes.

import { createHash } from 'node:crypto';
import type { GameData } from '@nomarque/data';
import * as prettier from 'prettier';
import {
  parseBuildings,
  parseCards,
  parseExpeditions,
  parseHouses,
  parseParameters,
  parseResources,
  ImportDataError,
  type CardLabels,
} from './parse';
import { gameDataSchema } from './schemas';

/** Names relative to data/economie, sorted as required by the version hash. */
export const SOURCE_FILES = [
  'batiments.csv',
  'besoins_maisons.csv',
  'cartes.csv',
  'expeditions.csv',
  'maisons.csv',
  'parametres.csv',
  'ressources.csv',
] as const;

export type SourceFile = (typeof SOURCE_FILES)[number];

export type SourceBundle = Record<SourceFile, string>;

export interface FrLabels {
  resources: Record<string, string>;
  buildings: Record<string, string>;
  houses: Record<string, string>;
  expeditionRoutes: Record<string, string>;
  destinations: Record<string, string>;
  cards: Record<string, CardLabels>;
}

export interface BuiltGameData {
  data: GameData;
  labels: FrLabels;
}

const GENERATED_HEADER =
  '// Generated by nx run tools:import-data from data/economie. Do not edit.';

export const GAME_DATA_PATH = 'libs/data/src/generated/game-data.generated.ts';
export const FR_LABELS_PATH = 'libs/data/src/generated/fr.generated.ts';

export function computeVersion(sources: Record<string, string>): string {
  const hash = createHash('sha256');
  for (const file of SOURCE_FILES) {
    hash.update(sources[file]);
  }
  return hash.digest('hex').slice(0, 12);
}

export function buildGameData(sources: SourceBundle): BuiltGameData {
  const resources = parseResources(sources['ressources.csv']);
  const buildings = parseBuildings(sources['batiments.csv']);
  const houses = parseHouses(
    sources['maisons.csv'],
    sources['besoins_maisons.csv'],
  );
  const parameters = parseParameters(sources['parametres.csv']);
  const expeditions = parseExpeditions(sources['expeditions.csv']);
  const cards = parseCards(sources['cartes.csv']);

  const data: GameData = {
    version: computeVersion(sources),
    resources: resources.resources,
    buildings: buildings.buildings,
    houses: houses.houses,
    parameters,
    expeditions: expeditions.expeditions,
    cards: cards.cards,
  };

  const result = gameDataSchema.safeParse(data);
  if (!result.success) {
    const details = result.error.issues
      .map((issue) => {
        const path = issue.path.join('.');
        return `  - ${path === '' ? '(root)' : path}: ${issue.message}`;
      })
      .join('\n');
    throw new ImportDataError(`generated game data is invalid:\n${details}`);
  }

  const labels: FrLabels = {
    resources: resources.labels,
    buildings: buildings.labels,
    houses: houses.labels,
    expeditionRoutes: expeditions.routeLabels,
    destinations: expeditions.destinationLabels,
    cards: cards.labels,
  };

  return { data: result.data, labels };
}

async function format(source: string, filePath: string): Promise<string> {
  const config = await prettier.resolveConfig(filePath);
  return prettier.format(source, {
    ...(config ?? {}),
    filepath: filePath,
    parser: 'typescript',
  });
}

export async function renderGameDataFile(
  data: GameData,
  filePath: string,
): Promise<string> {
  const source = `${GENERATED_HEADER}
import type { GameData } from '../lib/types';

export const GAME_DATA: GameData = ${JSON.stringify(data, null, 2)};
`;
  return format(source, filePath);
}

export async function renderLabelsFile(
  labels: FrLabels,
  filePath: string,
): Promise<string> {
  const source = `${GENERATED_HEADER}
export const FR_LABELS = ${JSON.stringify(labels, null, 2)} as const;
`;
  return format(source, filePath);
}
